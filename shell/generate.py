"""Generate scanner-visible handlers and real gRPC bindings from the curated service catalog."""

import argparse
import collections
import hashlib
import json
import re
import subprocess
import tempfile
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULE = "example.com/protomap-fixtures"
HEADER = "// Code generated by fixture-generator. DO NOT EDIT.\n"
MANIFEST = ROOT / ".fixture-generated.json"


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def read_catalog():
    catalog = json.loads((ROOT / "catalog/services.json").read_text())
    if catalog.get("schema") != 1:
        raise ValueError("Unsupported catalog schema")
    domains, services, names, paths = {}, {}, {}, {}
    for domain in catalog["domains"]:
        key = domain["name"]
        if not re.fullmatch(r"[a-z]+", key) or key in domains or not domain["services"]:
            raise ValueError(f"Invalid, empty, or duplicate domain: {key}")
        domains[key] = domain
        for service in domain["services"]:
            name = service["name"]
            if not re.fullmatch(r"[A-Z][A-Za-z]+", name) or name in names:
                raise ValueError(f"Invalid or duplicate service name: {name}")
            if not re.fullmatch(r"[A-Z][A-Za-z]+", service["rpc"]) or not service["responsibility"].strip():
                raise ValueError(f"Missing operation or responsibility: {name}")
            path = f"services/{key}/{snake(name)}.go"
            if path.casefold() in paths:
                raise ValueError(f"Case-insensitive path collision: {path}")
            names[name] = True
            paths[path.casefold()] = True
            services[f"{key}.{name}"] = {**service, "domain": key}
    if not 1 <= len(services) <= 5000:
        raise ValueError("The catalog must contain between 1 and 5,000 services")
    auth_service = catalog.get("shared_auth_service")
    if auth_service is not None and auth_service not in services:
        raise ValueError(f"Unknown shared auth service: {auth_service}")
    incoming, neighbors = collections.Counter(), collections.defaultdict(list)
    for name, service in services.items():
        peers = service["peers"]
        if len(peers) != len(dict.fromkeys(peers)) or name in peers:
            raise ValueError(f"Peers must be distinct other services: {name}")
        if name == auth_service:
            if peers:
                raise ValueError("The shared auth service must have no downstream peers")
        else:
            business_peers = [peer for peer in peers if peer != auth_service]
            if not 2 <= len(business_peers) <= 5:
                raise ValueError(f"Each business service must call 2-5 business peers: {name}")
            if auth_service is not None and auth_service not in peers:
                raise ValueError(f"Missing shared auth dependency: {name}")
        for peer in peers:
            if peer not in services:
                raise ValueError(f"Unknown peer {peer} of {name}")
            incoming[peer] += 1
            neighbors[name].append(peer)
            neighbors[peer].append(name)
    missing = sorted(name for name in services if name not in incoming)
    if missing:
        raise ValueError(f"Services with no callers: {missing}")
    visited, queue = {}, collections.deque([min(services)])
    while queue:
        node = queue.popleft()
        if node not in visited:
            visited[node] = True
            queue.extend(sorted(peer for peer in neighbors[node] if peer not in visited))
    if sorted(visited) != sorted(services):
        raise ValueError("The service graph must be connected")
    # A service may implement more methods than its main one, each calling methods of its peers that it names.
    for name, service in services.items():
        rpcs = {service["rpc"]: True}
        for operation in service.get("operations", []):
            rpc = operation["rpc"]
            if not re.fullmatch(r"[A-Z][A-Za-z]+", rpc) or rpc in rpcs or not operation["responsibility"].strip():
                raise ValueError(f"Invalid, duplicate, or undescribed operation of {name}: {rpc}")
            rpcs[rpc] = True
    for name, service in services.items():
        for operation in service.get("operations", []):
            calls = operation["calls"]
            if len(calls) != len(dict.fromkeys(calls)):
                raise ValueError(f"Operation calls must be distinct: {name}.{operation['rpc']}")
            for call in calls:
                peer, _, rpc = call.rpartition(".")
                if peer not in service["peers"] or rpc not in list_rpcs(services[peer]):
                    raise ValueError(f"Operation {name}.{operation['rpc']} calls {call}, no method of its peers")
    return domains, services


def list_rpcs(service):
    """The methods a service implements: its main one, then its operations."""
    return [service["rpc"], *(operation["rpc"] for operation in service.get("operations", []))]


def list_calls(services, service):
    """Each method of a service with the peer methods it calls: the main one each peer's main method."""
    yield service["rpc"], [(peer, services[peer]["rpc"]) for peer in sorted(service["peers"])]
    for operation in service.get("operations", []):
        yield operation["rpc"], [tuple(call.rpartition(".")[::2]) for call in operation["calls"]]


def render_handler(services, qualified, service, rpc, calls, reply):
    """A handler that, with hops left, calls each of its peer methods and keeps the email of each reply."""
    lines = [f"func (s *{service['name']}Server) {rpc}(ctx context.Context, req *commonpb.Request) "
             "(*commonpb.Response, error) {", "\tif err := network.ValidateRequest(ctx, req); err != nil {",
             "\t\treturn nil, err", "\t}", "\tresult := &commonpb.Response{",
             "\t\tSubjectId: req.GetSubjectId(),", "\t\tEmail: req.GetEmail(),",
             f'\t\tVisitedServices: []string{{"{qualified}"}},', "\t}"]
    if calls:
        lines.extend(["\tif req.GetRemainingHops() == 0 {", "\t\treturn result, nil", "\t}",
                      "\tpeerRequest := &commonpb.Request{", "\t\tTenantId: req.GetTenantId(),",
                      "\t\tSubjectId: req.GetSubjectId(),", "\t\tEmail: req.GetEmail(),",
                      "\t\tRemainingHops: req.GetRemainingHops() - 1,", "\t}"])
    for peer, method in calls:
        target = services[peer]
        variable = reply(target, method)
        lines.extend([f'\t{variable}, err := s.peer{target["name"]}.{method}(ctx, peerRequest)',
                      "\tif err != nil {", f'\t\treturn nil, network.PeerError("{peer}", err)', "\t}",
                      f"\tresult.Email = {variable}.GetEmail()",
                      f"\tresult.VisitedServices = append(result.VisitedServices, {variable}.GetVisitedServices()...)"])
    lines.extend(["\treturn result, nil", "}", ""])
    return lines


def render(domains, services):
    files = {}
    files["proto/common/common.proto"] = '''syntax = "proto3";
package fixture.common.v1;
option go_package = "example.com/protomap-fixtures/gen/common;commonpb";

// Synthetic business data and controls for bounded fixture workflows.
message Request {
  string tenant_id = 1;
  string subject_id = 2;
  string email = 3;
  int32 remaining_hops = 4;
}

message Response {
  string subject_id = 1;
  string email = 2;
  repeated string visited_services = 3;
}
'''
    for domain in sorted(domains):
        entries = [service for key, service in sorted(services.items()) if service["domain"] == domain]
        lines = ['syntax = "proto3";', f"package fixture.{domain}.v1;",
                 f'option go_package = "{MODULE}/gen/{domain};{domain}pb";', 'import "common/common.proto";', ""]
        for service in entries:
            lines.extend([f"// {service['responsibility']}", f"service {service['name']} {{",
                          f"  rpc {service['rpc']}(fixture.common.v1.Request) returns (fixture.common.v1.Response);"])
            for operation in service.get("operations", []):
                lines.extend([f"  // {operation['responsibility']}",
                              f"  rpc {operation['rpc']}(fixture.common.v1.Request) "
                              "returns (fixture.common.v1.Response);"])
            lines.extend(["}", ""])
        files[f"proto/{domain}/services.proto"] = "\n".join(lines)
        imports = {domain: True}
        for service in entries:
            imports.update({services[peer]["domain"]: True for peer in service["peers"]})
        lines = [HEADER, f"package {domain}", "", "import (", '\t"google.golang.org/grpc"',
                 f'\t"{MODULE}/internal/network"']
        lines.extend(f'\t{key}pb "{MODULE}/gen/{key}"' for key in sorted(imports))
        lines.extend([")", "", "func Register(registrar grpc.ServiceRegistrar, pool network.Pool) {"])
        for service in entries:
            name = service["name"]
            lines.append(f"\t{domain}pb.Register{name}Server(registrar, &{name}Server{{")
            for peer in sorted(service["peers"]):
                target = services[peer]
                key = target["domain"]
                lines.append(f'\t\tpeer{target["name"]}: {key}pb.New{target["name"]}Client(pool["{key}"]),')
            lines.extend(["\t})", ""])
        lines.extend(["}", ""])
        files[f"services/{domain}/register.go"] = "\n".join(lines)
    for qualified, service in sorted(services.items()):
        domain, name = service["domain"], service["name"]
        imports = {domain: True, **{services[peer]["domain"]: True for peer in service["peers"]}}
        lines = [HEADER, f"package {domain}", "", "import (", '\t"context"',
                 f'\tcommonpb "{MODULE}/gen/common"', f'\t"{MODULE}/internal/network"']
        lines.extend(f'\t{key}pb "{MODULE}/gen/{key}"' for key in sorted(imports))
        lines.extend([")", "", f"// {service['responsibility']}", f"type {name}Server struct {{",
                      f"\t{domain}pb.Unimplemented{name}Server"])
        for peer in sorted(service["peers"]):
            target = services[peer]
            lines.append(f'\tpeer{target["name"]} {target["domain"]}pb.{target["name"]}Client')
        lines.extend(["}", ""])
        # The main method's replies are named for their services, and an operation's, which may call several methods
        # of one service, for their methods too.
        main, *operations = list_calls(services, service)
        lines.extend(render_handler(services, qualified, service, *main,
                                    lambda target, method: "reply" + target["name"]))
        for (operation, calls), described in zip(operations, service.get("operations", [])):
            lines.extend([f"// {described['responsibility']}", *render_handler(
                services, qualified, service, operation, calls,
                lambda target, method: "reply" + target["name"] + method)])
        files[f"services/{domain}/{snake(name)}.go"] = "\n".join(lines)
    lines = [HEADER, "package registry", "", "import (", '\t"google.golang.org/grpc"',
             f'\t"{MODULE}/internal/network"']
    lines.extend(f'\t"{MODULE}/services/{domain}"' for domain in sorted(domains))
    lines.extend([")", "", "var Domains = []string{"])
    lines.extend(f'\t"{domain}",' for domain in sorted(domains))
    lines.extend(["}", "", "func RegisterDomain(domain string, registrar grpc.ServiceRegistrar, pool network.Pool) {",
                  "\tswitch domain {"])
    for domain in sorted(domains):
        lines.extend([f'\tcase "{domain}":', f"\t\t{domain}.Register(registrar, pool)"])
    lines.extend(["\t}", "}", "", "var Services = []network.Service{"])
    for qualified, service in sorted(services.items()):
        method = f"/fixture.{service['domain']}.v1.{service['name']}/{service['rpc']}"
        lines.extend(["\t{", f'\t\tName: "{qualified}",', f'\t\tDomain: "{service["domain"]}",',
                      f'\t\tMethod: "{method}",', "\t\tPeers: []string{"])
        lines.extend(f'\t\t\t"{peer}",' for peer in sorted(service["peers"]))
        lines.extend(["\t\t},", "\t},"])
    lines.extend(["}", ""])
    files["internal/registry/catalog.go"] = "\n".join(lines)
    return files


def generate(check):
    domains, services = read_catalog()
    files = render(domains, services)
    version = subprocess.check_output(["protoc", "--version"], text=True).strip()
    if version != "libprotoc 36.2":
        raise ValueError(f"Generation requires protoc 36.2, found {version}")
    with tempfile.TemporaryDirectory(prefix="protomap-fixtures-") as folder:
        temp = Path(folder)
        for path, content in files.items():
            destination = temp / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content)
        proto_files = sorted(str(temp / path) for path in files if path.endswith(".proto"))
        subprocess.run([
            "protoc", f"-I{temp / 'proto'}", f"--go_out={temp}", f"--go_opt=module={MODULE}",
            f"--go-grpc_out={temp}", f"--go-grpc_opt=module={MODULE}",
            f"--plugin=protoc-gen-go={ROOT / '.cache/bin/protoc-gen-go'}",
            f"--plugin=protoc-gen-go-grpc={ROOT / '.cache/bin/protoc-gen-go-grpc'}", *proto_files,
        ], check=True)
        go_files = sorted(str(path) for path in temp.rglob("*.go"))
        for path in map(Path, go_files):
            lines = []
            for line in path.read_text().splitlines():
                if len(line) > 120 and line.lstrip().startswith("// "):
                    prefix = line[:len(line) - len(line.lstrip())] + "// "
                    lines.extend(prefix + part for part in textwrap.wrap(
                        line.lstrip()[3:], width=120-len(prefix), break_long_words=False, break_on_hyphens=False))
                else:
                    lines.append(line)
            path.write_text("\n".join(lines) + "\n")
        subprocess.run(["gofmt", "-w", *go_files], check=True)
        output = {str(path.relative_to(temp)): path.read_bytes() for path in sorted(temp.rglob("*")) if path.is_file()}
    manifest = {path: hashlib.sha256(content).hexdigest() for path, content in sorted(output.items())}
    previous = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    changed = [path for path, content in output.items() if not (ROOT / path).is_file()
               or (ROOT / path).read_bytes() != content]
    stale = sorted(path for path in previous if path not in output)
    if check:
        if changed or stale or previous != manifest:
            raise ValueError(f"Generation differs: {len(changed)} changed/missing files, {len(stale)} stale files")
    else:
        for path in changed:
            if path not in previous and (ROOT / path).exists():
                raise ValueError(f"Refusing to overwrite an unowned file: {path}")
        for path in stale:
            destination = ROOT / path
            if destination.exists() and hashlib.sha256(destination.read_bytes()).hexdigest() != previous[path]:
                raise ValueError(f"Refusing to delete an edited obsolete file: {path}")
        for path in stale:
            (ROOT / path).unlink(missing_ok=True)
        for path in changed:
            destination = ROOT / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(output[path])
        MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    edges = sum(len(service["peers"]) for service in services.values())
    print(f"{'Verified' if check else 'Generated'} {len(services)} services, {len(domains)} domains, {edges} peer edges")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify catalog output without changing generated files")
    args = parser.parse_args()
    try:
        generate(args.check)
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Generation failed: {error}\n")


if __name__ == "__main__":
    main()
